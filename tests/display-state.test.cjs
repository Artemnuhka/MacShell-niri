const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const d = vm.createContext({});
vm.runInContext(fs.readFileSync(`${__dirname}/../DisplayState.js`, 'utf8'), d);
const screens = [{name:'eDP-1',x:0,y:0,width:1536,height:960},{name:'DP-1',x:-1920,y:0,width:1920,height:1080},{name:'DP-2',x:1536,y:-300,width:1080,height:1920}];
assert.equal(d.primary(screens,'DP-2','eDP-1'),'DP-2');
assert.equal(d.target(screens,'@focused','DP-1','DP-2'),'DP-2');
assert.equal(d.target(screens,'unplugged','DP-1',''),'DP-1');
assert.equal(d.target([screens[0]],'DP-1','DP-1',''),'eDP-1');
const outputs = {'DP-2':{logical:{x:1536,y:-300,width:1080,height:1920,scale:2,transform:'90'}},'eDP-1':{logical:{x:0,y:0,width:1536,height:960,scale:1.5}},'DP-1':{logical:{x:-1920,y:0,width:1920,height:1080,scale:1}},disabled:{logical:null}};
const monitors=d.monitors(outputs,[{output:'DP-2',is_active:true,id:9}]);
assert.equal(monitors.length,3);assert.equal(monitors[2].height,3840);assert.equal(monitors[2].activeWorkspace.id,9);assert.equal(monitors[1].width,2304);
const widgets=[{id:'a',screen:'DP-1',x:32,y:64,size:'s'},{id:'b',screen:'DP-2',x:32,y:64,size:'s'},{id:'c',screen:'DP-2',x:900,y:1800,size:'s'}];
const before=JSON.stringify(widgets), dims=()=>({w:185,h:185});
const connected=d.widgetPositions(widgets,screens,'DP-1',dims);
const unplugged=d.widgetPositions(widgets,[screens[0]],'DP-1',dims);
assert.equal(unplugged.b.screen,'eDP-1');assert.notEqual(unplugged.a.x+','+unplugged.a.y,unplugged.b.x+','+unplugged.b.y);assert(unplugged.c.y<=960-185-8);
const reconnected=d.widgetPositions(widgets,screens,'DP-1',dims);
assert.equal(JSON.stringify(connected),JSON.stringify(reconnected));assert.equal(before,JSON.stringify(widgets));
console.log('Display state: 3 screens, fractional scales, portrait, negative positions and reconnect passed.');

const lock = vm.createContext({});
vm.runInContext(fs.readFileSync(`${__dirname}/../MacLock/DisplayState.js`, 'utf8'), lock);
const desktop = [{name:'DVI-D-1',x:0,y:0},{name:'HDMI-A-1',x:1280,y:0}];
assert.equal(lock.lockPrimary(desktop,'HDMI-A-1','DVI-D-1','DVI-D-1'),'HDMI-A-1');
assert.equal(lock.lockPrimary(desktop,'','DVI-D-1','HDMI-A-1'),'DVI-D-1');
assert.equal(lock.lockPrimary([desktop[0]],'HDMI-A-1','HDMI-A-1','DVI-D-1'),'DVI-D-1');
assert.equal(lock.lockPrimary(desktop,'HDMI-A-1','DVI-D-1','DVI-D-1'),'HDMI-A-1');
assert.equal(lock.lockPrimary(desktop,'DVI-D-1','HDMI-A-1','HDMI-A-1'),'DVI-D-1');
assert.equal(lock.lockPrimary([], 'HDMI-A-1','DVI-D-1',''), '');
console.log('MacLock: saved primary wins over focus/enumeration, delayed settings, unplug/reconnect and primary changes passed.');
